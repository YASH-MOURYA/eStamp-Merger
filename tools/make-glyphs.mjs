// Generates src/lib/glyphs.js: vector outlines of printable ASCII from Arimo Regular
// (metric-compatible with Arial/Helvetica; Apache License 2.0).
//   npm i -D @expo-google-fonts/arimo @pdf-lib/fontkit
//   node tools/make-glyphs.mjs node_modules/@expo-google-fonts/arimo/400Regular/Arimo_400Regular.ttf
import fs from "node:fs";
import fontkit from "@pdf-lib/fontkit";

const file = process.argv[2];
if (!file) throw new Error("usage: node tools/make-glyphs.mjs <Arimo_400Regular.ttf>");
const font = fontkit.create(fs.readFileSync(file));
const r = (n) => Math.round(n);

const glyphs = {};
for (let cp = 32; cp <= 126; cp++) {
  const glyph = font.glyphForCodePoint(cp);
  let x = 0, y = 0;
  const out = [];
  for (const { command, args } of glyph.path.commands) {
    if (command === "moveTo") { out.push(`M${r(args[0])} ${r(args[1])}`); [x, y] = args; }
    else if (command === "lineTo") { out.push(`L${r(args[0])} ${r(args[1])}`); [x, y] = args; }
    else if (command === "quadraticCurveTo") {
      // quadratic -> cubic so a single curve operator is enough
      const [qx, qy, ex, ey] = args;
      out.push(`C${r(x + (2 / 3) * (qx - x))} ${r(y + (2 / 3) * (qy - y))} ${r(ex + (2 / 3) * (qx - ex))} ${r(ey + (2 / 3) * (qy - ey))} ${r(ex)} ${r(ey)}`);
      [x, y] = [ex, ey];
    } else if (command === "bezierCurveTo") { out.push(`C${args.map(r).join(" ")}`); [x, y] = args.slice(4); }
    else if (command === "closePath") out.push("Z");
  }
  glyphs[String.fromCharCode(cp)] = { a: r(glyph.advanceWidth), p: out.join("") };
}

const src = `// AUTO-GENERATED by tools/make-glyphs.mjs - do not edit.
// Glyph outlines: Arimo Regular (Apache License 2.0), units per em = ${font.unitsPerEm}.
export const UPM = ${font.unitsPerEm};
export const GLYPHS = ${JSON.stringify(glyphs)};
`;
fs.writeFileSync(new URL("../src/lib/glyphs.js", import.meta.url), src);
console.log("glyphs:", Object.keys(glyphs).length, "bytes:", src.length);
